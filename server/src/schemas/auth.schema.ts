import { z } from 'zod';

/**
 * Схемы валидации модуля авторизации.
 *
 * Вынесены отдельно от routes: выведенные из них типы нужны и контроллеру,
 * и сервису, а импортировать типы из файла с роутами — значит развернуть
 * зависимости в обратную сторону.
 */

/**
 * ВАЖНО про верхнюю границу пароля.
 *
 * bcrypt обрезает вход на 72 БАЙТАХ и делает это молча. Без явной проверки
 * пароль «72 байта + ещё что-то» превратился бы в свои первые 72 байта, и два
 * разных длинных пароля открывали бы один аккаунт.
 *
 * Считаем именно байты, а не символы: кириллица в UTF-8 занимает 2 байта,
 * то есть 40 русских букв — это уже 80 байт, и проверка по .length здесь врёт.
 */
const MAX_PASSWORD_BYTES = 72;

const password = z
  .string({ error: 'Укажите пароль' })
  .min(8, 'Пароль должен быть не короче 8 символов')
  .refine(
    (value) => Buffer.byteLength(value, 'utf8') <= MAX_PASSWORD_BYTES,
    `Пароль слишком длинный (максимум ${MAX_PASSWORD_BYTES} байт; кириллица считается по 2 байта на символ)`,
  );

/**
 * Email приводим к нижнему регистру и обрезаем пробелы ДО записи в БД, иначе
 * «User@mail.ru» и «user@mail.ru» станут двумя аккаунтами вопреки @unique.
 *
 * Порядок здесь критичен и неочевиден: запись `z.email().trim().toLowerCase()`
 * НЕ работает — Zod сначала проверяет формат и только потом применяет
 * преобразования, поэтому « User@Mail.RU » с пробелами отвалится как
 * «некорректный email», не дойдя до trim. Через .pipe() порядок обратный.
 */
const email = z
  .string({ error: 'Укажите email' })
  .trim()
  .toLowerCase()
  .pipe(z.email('Некорректный email').max(255, 'Email слишком длинный'));

export const registerSchema = z.object({
  email,
  password,
});

export const loginSchema = z.object({
  email,
  // На логине к паролю применяем только базовую проверку: правила сложности
  // могли измениться с момента регистрации, и старый пароль обязан работать.
  password: z.string({ error: 'Укажите пароль' }).min(1, 'Введите пароль'),
});

export type RegisterInput = z.infer<typeof registerSchema>;
export type LoginInput = z.infer<typeof loginSchema>;
